let maior = Math.max(6, 12, 28, 55, 8); //O método Math.max() retorna o maior número de um conjunto de números.
console.log(maior);

let menor = Math.min(6, 12, 28, 55, 8); //O método Math.min() retorna o menor número de um conjunto de números.
console.log(menor);

let arredondar = Math.round(5.985379821); //O método Math.round() retorna o valor de um número arredondado para o inteiro mais próximo.
console.log(arredondar);

let arredondarParaCima = Math.ceil(2.39728651); //O método Math.ceil() retorna o inteiro maior ou igual mais próximo de um número.
console.log(arredondarParaCima);

